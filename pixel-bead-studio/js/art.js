/** 把字符画转成 grid 对象（不依赖 grid.js，保持数据层独立） */
export function artToGrid(item) {
  const rows = item.art.map((r) => r.padEnd(item.art[0].length, '.').slice(0, item.art[0].length));
  const cols = rows[0].length;
  const CHARS = '0123456789abcdefghijklmnopqrstuvwxyz';
  const grid = new Int8Array(cols * rows.length).fill(-1);
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      const i = CHARS.indexOf(ch);
      if (i >= 0 && i < item.palette.length) grid[y * cols + x] = i;
    });
  });
  return {
    cols, rows: rows.length, palette: item.palette.slice(), grid,
    get(x, y) { return x < 0 || y < 0 || x >= cols || y >= rows.length ? -1 : grid[y * cols + x]; },
    set(x, y, v) { if (x >= 0 && y >= 0 && x < cols && y < rows.length) grid[y * cols + x] = v; },
    clone() { const c = artToGrid(item); return c; },
    idx(x, y) { return y * cols + x; },
    counts() {
      const counts = new Array(item.palette.length).fill(0);
      let filled = 0;
      for (const v of grid) if (v >= 0) { counts[v]++; filled++; }
      return { counts, filled, colors: counts.filter((n) => n > 0).length };
    },
    toRowStrings() {
      const out = [];
      for (let y = 0; y < rows.length; y++) {
        let s = '';
        for (let x = 0; x < cols; x++) { const v = grid[y * cols + x]; s += v < 0 ? '.' : CHARS[v] || '.'; }
        out.push(s);
      }
      return out;
    },
  };
}

export const LIBRARY = ART.map((a) => ({ ...a, grid: artToGrid(a) }));

/* 用户自定义图案（localStorage 持久化） */
const LS_KEY = 'pbs.myWorks.v1';

export function loadWorks() {
  try { return JSON.parse(localStorage.getItem(LS_KEY) || '[]'); } catch { return []; }
}

export function saveWork(work) {
  const list = loadWorks();
  list.unshift({ ...work, savedAt: Date.now() });
  localStorage.setItem(LS_KEY, JSON.stringify(list.slice(0, 40)));
  return list;
}

export function deleteWork(id) {
  const list = loadWorks().filter((w) => w.id !== id);
  localStorage.setItem(LS_KEY, JSON.stringify(list));
  return list;
}
